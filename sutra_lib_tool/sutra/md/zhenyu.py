# ── 干支纪年 ────────────────────────────────────────────────────────
GAN = '甲乙丙丁戊己庚辛壬癸'
ZHI = '子丑寅卯辰巳午未申酉戌亥'


def _sexagenary(g: int, z: int) -> int:
    """干支之六十甲子序号。"""
    for n in range(60):
        if n % 10 == g and n % 12 == z:
            return n
    raise ValueError('干支不合法')


def ganzhi_year(gz: str, anchor: str = '己卯', anchor_year: int = 1579) -> int:
    """干支纪年折为西历年。

    :param gz: 干支（如「丁丑」）
    :param anchor: 锚点之干支
    :param anchor_year: 锚点之西历年
    """
    gi = _sexagenary(GAN.index(gz[0]), ZHI.index(gz[1]))
    ai = _sexagenary(GAN.index(anchor[0]), ZHI.index(anchor[1]))
    return anchor_year + (gi - ai) % 60


