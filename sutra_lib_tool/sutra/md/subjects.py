# ── 检索索引 ────────────────────────────────────────────────────────────────
def build_index():
    """档号 → (所属目录, 标题, 相对 ROOT 之路径)。"""
    idx = {}
    for d in sorted(os.listdir(SUTRA)):
        p = SUTRA / d
        if not os.path.isdir(p):
            continue
        for f in sorted(os.listdir(p)):
            if not f.endswith(".md"):
                continue
            fp = p / f
            try:
                with open(fp, encoding="utf-8") as fh:
                    title = fh.readline().lstrip("#").strip()
            except Exception:
                continue
            idx[f[:-3]] = (d, title, os.path.relpath(fp, ROOT))
    return idx


def norm(s):
    """标题归一：去括注、去标点空白。"""
    s = re.sub(r"[（(].*?[)）]", "", s)
    s = re.sub(r"[\s·．\.,，。、:：]", "", s)
    return s


VARIANT = {"咒": "呪", "罗": "攞", "毗": "毘", "画": "畫", "澁": "涩", "麼": "么", "摩": "摩"}


def variant(t):
    return "".join(VARIANT.get(c, c) for c in t)


def real_title(code, given):
    """若给定标题与索引标题仅异体字差异，则采用库中标题，并保留原有括注。"""
    real = IDX[code][1]
    m = re.match(r"^(.*?)((?:（[^）]*）)*)$", given)
    core, ann = m.group(1), m.group(2)
    real_core = re.sub(r"[（(][^）)]*[）)]", "", real)
    if variant(core) == variant(real_core):
        if ann and ann not in real:
            return real + ann
        return real
    return given


def link(code, title):
    """生成带链接的条目；code 不存在时抛错以防臆造。

    链接相对专题档所在目录（`sutra_subject/recipe/`）而写，
    故须上溯至阅读版根，再入 `sutra_md/`。
    """
    if code not in IDX:
        raise KeyError(f"档号不存在：{code}")
    d, _t, rel = IDX[code]
    return f"- [{title}]({LINK_PREFIX}/{rel})"


def plain(title):
    return f"- {title}"


