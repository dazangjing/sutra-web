# ── 子命令：index ───────────────────────────────────────────────────────────
def index_main(argv=None) -> int:
    """生成 recipe/索引.md：列出各专题文件、章节结构与链接统计。"""
    ap = argparse.ArgumentParser(
        prog="main.py md subjects index",
        description="生成 recipe/索引.md：列出各专题文件、章节结构与链接统计。")
    ap.add_argument('--dir', default=str(SUBJ), help='专题目录')
    args = ap.parse_args(argv)

    subj = pathlib.Path(args.dir)
    files = sorted(
        f for f in os.listdir(subj)
        if f.endswith(".md") and f not in ("README.md", "索引.md")
    )
    order = [
        "佛学入门指南",
        "净土宗", "华严宗", "禅宗", "天台宗", "法华专辑",
        "地藏菩萨专辑", "观音菩萨专辑", "弥勒菩萨专辑", "律宗", "唯识宗",
        "中观宗", "密教宗", "方志", "图文并茂",
    ]
    files.sort(key=lambda f: (order.index(f[:-3]) if f[:-3] in order else 99, f))
    out = ["# 专题索引", ""]
    out.append("本目录按宗派／菩萨专题编纂佛典目录，条目按该宗**修行实践的主要特点**分类，")
    out.append("并链接至本库 `sutra_md/` 对应典籍。编写规范见 [README.md](README.md)。")
    out.append("")
    out.append("| 专题 | 小节数 | 链接典籍数 |")
    out.append("| --- | --- | --- |")
    toc = []
    for f in files:
        with open(subj / f, encoding="utf-8") as fh:
            text = fh.read()
        links = len(LINK_RE.findall(text))
        secs = H2_RE.findall(text)
        out.append(f"| [{f[:-3]}]({f}) | {len(secs)} | {links} |")
        toc.append((f[:-3], secs))
    out.append("")
    out.append("## 分篇目录")
    out.append("")
    for title, secs in toc:
        out.append(f"### {title}")
        out.append("")
        for s in secs:
            out.append(f"- {s}")
        out.append("")
    path = subj / "索引.md"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"已写出 {path}（{len(files)} 个专题）")
    return 0


# ── 子命令：check ───────────────────────────────────────────────────────────
def check_main(argv=None) -> int:
    """校验 recipe/*.md 中指向 sutra_md 的相对链接是否可达。"""
    ap = argparse.ArgumentParser(
        prog="main.py md subjects check",
        description="校验 recipe/*.md 中指向 sutra_md 的相对链接是否可达。")
    ap.add_argument('targets', nargs='*', help='校验指定专题（不含扩展名）')
    ap.add_argument('--dir', default=str(SUBJ), help='专题目录')
    args = ap.parse_args(argv)

    subj = pathlib.Path(args.dir)
    targets = args.targets
    files = []
    for f in sorted(os.listdir(subj)):
        if not f.endswith(".md") or f == "README.md":
            continue
        if targets and f[:-3] not in targets:
            continue
        files.append(f)
    bad = 0
    total = 0
    for f in files:
        path = subj / f
        with open(path, encoding="utf-8") as fh:
            for i, line in enumerate(fh, 1):
                for m in LINK_RE.finditer(line):
                    total += 1
                    target = os.path.normpath(os.path.join(subj, m.group(1)))
                    if not os.path.isfile(target):
                        bad += 1
                        print(f"{f}:{i}: 失效链接 {m.group(1)}")
    print(f"共检查 {len(files)} 个文件、{total} 条链接，失效 {bad} 条")
    return 1 if bad else 0


# ── 子命令：search ──────────────────────────────────────────────────────────
def search_main(argv=None) -> int:
    """按标题关键词检索 sutra_md 库中的佛典，返回档号、路径与标题。"""
    ap = argparse.ArgumentParser(
        prog="main.py md subjects search",
        description="按标题关键词检索 sutra_md 库中的佛典。")
    ap.add_argument('keywords', nargs='*', help='标题须含之关键词')
    ap.add_argument('--exact', action='store_true', help='精确匹配（去括注、去标点）')
    args = ap.parse_args(argv)

    idx = build_index()
    if args.exact:
        keys = {norm(a) for a in args.keywords}
        for k, (d, t, rel) in sorted(idx.items()):
            if norm(t) in keys:
                print(f"{k}\t{d}\t{t}\t{rel}")
        return 0
    if not args.keywords:
        print("请给出关键词", file=sys.stderr)
        return 0
    for k, (d, t, rel) in sorted(idx.items()):
        if all(a in t for a in args.keywords):
            print(f"{k}\t{d}\t{t}\t{rel}")
    return 0


