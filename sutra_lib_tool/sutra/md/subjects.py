def load_appendix(path):
    """读取《禅宗全书》目录附录档，回传其附录正文。

    :param path: 附录档路径
    :raises SystemExit: 档案不存在或不含标记时，给出可操作之提示
    """
    p = pathlib.Path(path)
    if not p.exists():
        raise SystemExit(
            f"错误：找不到附录档案 {p}\n"
            "  禅宗专题之附录（《禅宗全书》目录）为外部输入，须另行备置。\n"
            f"  可用 --appendix 指定其路径（内须含「{APPENDIX_MARK}」标记）。")
    raw = p.read_text(encoding="utf-8").rstrip("\n")
    if APPENDIX_MARK not in raw:
        raise SystemExit(
            f"错误：附录档案 {p} 中找不到「{APPENDIX_MARK}」标记。\n"
            "  须确认其内容确为《禅宗全书》之目录。")
    return raw[raw.index(APPENDIX_MARK):]


def resolve_appendix(appendix_path=None):
    """决定附录来源档，并读其附录正文。

    优先用 `--appendix` 所指定者；次用 `sutra_subject/other/` 下之
    《禅宗全书》目录档；皆无者，就既有专题档中取之——
    **读档必在写出专题档之前**，否则同档覆写将自毁其源。

    :param appendix_path: 明定之附录档路径
    :return: (路径, 附录正文)
    """
    if appendix_path:
        p = pathlib.Path(appendix_path)
        if not p.exists():
            raise SystemExit(
                f"错误：找不到附录档案 {p}\n"
                "  禅宗专题之附录（《禅宗全书》目录）为外部输入，须另行备置。\n"
                f"  其内须含「{APPENDIX_MARK}」标记。")
        return p, load_appendix(p)
    p = pathlib.Path(OTHER) / APPENDIX_DEFAULT
    if p.exists():
        return p, load_appendix(p)
    existing = SUBJ / "禅宗.md"
    if not existing.exists():
        raise SystemExit(
            f"错误：找不到附录档案 {p}\n"
            "  禅宗专题之附录（《禅宗全书》目录）为外部输入，须另行备置。\n"
            f"  可用 --appendix 指定其路径（内须含「{APPENDIX_MARK}」标记）。")
    return existing, load_appendix(existing)


def build_chan(appendix_text=None):
    """生成禅宗专题档；附录之条目尽量与库中档案对映成链接。

    :param appendix_text: 附录正文（已读出者）
    """
    parts = ["# 禅宗", "", CHAN_INTRO, ""]
    pending = None
    for item in CHAN:
        if isinstance(item, tuple):
            pending = item
            continue
        heading, note = pending
        pending = None
        parts.append(heading)
        parts.append("")
        parts.append(note)
        parts.append("")
        parts.append(render(item))
        parts.append("")
    parts.append(APPENDIX_HEADING)
    parts.append("")
    if appendix_text is None:
        _p, appendix_text = resolve_appendix()
    # 附录条目与库中档案对映，成可点击之链接
    from sutra.md.appendix import link_appendix
    text = "\n".join(parts + [appendix_text, ""])
    text, stat = link_appendix(text)
    print(f"附录：条目 {stat['entries']}　已链接 {stat['linked']}　"
          f"未收本库 {stat['missed']}")
    return text.rstrip("\n") + "\n"


