COMMANDS = {
    'build': build_main,
    'index': index_main,
    'check': check_main,
    'search': search_main,
}


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ('-h', '--help'):
        print('subjects 子命令：')
        print('  build   生成 recipe/禅宗.md 与 recipe/密教宗.md')
        print('  index   生成 recipe/索引.md')
        print('  check   校验专题中指向 sutra_md 的相对链接')
        print('  search  按标题关键词检索 sutra_md 库中的佛典')
        return 0
    sub = argv[0]
    if sub not in COMMANDS:
        print(f'未知 subjects 子命令：{sub}\n', file=sys.stderr)
        return 2
    return COMMANDS[sub](argv[1:]) or 0


