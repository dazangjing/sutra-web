def with_attr(code, title):
    """若库中有确切署名，按库中署名补入括注（不臆造）。"""
    a = ATTR.get(code)
    if not a:
        return title
    if "（" in title:
        return title
    return f"{title}（{a}）"

def render(items, use_real=False):
    out = []
    for it in items:
        if isinstance(it, tuple):
            code, title = it
            if use_real:
                title = real_title(code, title)
            title = with_attr(code, title)
            out.append(link(code, title))
        else:
            out.append(plain(it))
    return "\n".join(out)


