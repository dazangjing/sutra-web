def core(name):
    """剥住地与称谓，得法名核心；字异者按 ALIAS 归一。"""
    name = name.translate(VARIANT)
    n = TITLE_RE.sub("", name).strip()
    if n in ALIAS:
        return ALIAS[n]
    n = GEO_RE.sub("", n)
    n = re.sub(r"(?:府|寺|院|堂|庵|阁|苑)$", "", n)
    n = re.sub(r"^(?:大|小|老)", "", n).strip()
    return ALIAS.get(n, n)


def subseq(short, long):
    it = iter(long)
    return all(c in it for c in short)


def same_person(a, b):
    """判二人是否同指：核心全等，或短者为长者之子序列（法名含字号之常例）。"""
    ca, cb = core(a), core(b)
    if not ca or not cb:
        return False
    if ca == cb:
        return True
    return subseq(ca, cb) or subseq(cb, ca)


