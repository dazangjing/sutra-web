def resolve_chains():
    """依 CHAIN_SPEC 于 X1571 题记中逐项定位师之节点。

    返回 (节点列表, 边列表)，边为 (师 id, 法嗣 id)。
    每项 (师简称, 法嗣节点 id, …)：题记「N世师法嗣弟子」给出师与法嗣，
    法嗣之节点即本项之 id，而师之节点为链中「以该师为法嗣」的那一项
    ——即前一项的 id；链首之师取 CHAIN_HEAD_MASTER。
    凡题记与列表不合者，不立其边，俾复核时暴露出来。
    """
    nodes, edges = [], []
    for sectname, (sect_tail, chain) in CHAIN_SPEC.items():
        prev = CHAIN_HEAD_MASTER[sectname]
        for i, item in enumerate(chain):
            master, nid, label, school = item[:4]
            hint = item[4] if len(item) > 4 else None
            r = G.find(sect_tail, master, hint)
            if not r:
                raise SystemExit(f"X1571 未找到：{sectname} {master}")
            nodes.append(dict(id=nid, name=r["child"], label=label,
                              sub=f"{sect_tail}{r['gen'] + 1}世", school=school,
                              src=f"X1571「{r['quote']}」"))
            edges.append((prev, nid))
            prev = nid
    return nodes, edges


